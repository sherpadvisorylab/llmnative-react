const fs = require("fs");
const path = require("path");
const { THEMES_DIR } = require("./paths");

function toTsObject(value, indent) {
    return JSON.stringify(value, null, 4)
        .replace(/"([^"]+)":/g, "$1:")
        .replace(/"/g, "'")
        .replace(/\n/g, `\n${indent}`);
}

function emitFrameworkThemeFile(compiledTheme) {
    const outputPath = path.join(THEMES_DIR, `${compiledTheme.outputFileName}.ts`);
    const { mode, colors, dark } = compiledTheme.frameworkTheme;
    const { light: lightName, dark: darkName } = compiledTheme.sourceNames;

    // Status colors (destructive/success/warning/info) come from the default theme: VS Code has none.
    const fileContent = `// Generated by scripts/themes/compile-vscode-themes.js from the VS Code themes
// "${lightName}" (light) and "${darkName}" (dark). Do not edit: change the sources or the compiler.
import baseTheme from './default';
import type { ThemeDefinition } from '../src/Theme';

const definition: ThemeDefinition = {
    ...baseTheme,
    preset: {
        ...baseTheme.preset,
        mode: '${mode}',
        colors: {
            ...baseTheme.preset.colors,
            ...${toTsObject(colors, "            ")},
        },
        dark: {
            ...baseTheme.preset.dark,
            ...${toTsObject(dark, "            ")},
        },
    },
};

export default definition;
`;

    fs.writeFileSync(outputPath, fileContent, "utf8");
}

module.exports = {
    emitFrameworkThemeFile,
};
